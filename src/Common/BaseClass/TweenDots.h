//  片段模型（SceneClipModel）共用同一数据结构——纯数据头，无 Qt 对象依赖）。
//
//  单位约定：t_us 是【片段本地微秒】（0..length()；2026-11-10 微秒原生——
//  与 ms::Keyframe.t_us 同基直传，无换算层）；value 是业务域
//  真实值（X/Y/W/H 像素、旋转角度、不透明度 [0,1]）——归一化坐标只存在于
//  绘制/拖拽换算的一瞬间，本结构全程存真实值。
// ============================================================================

#pragma once

#include <vector>

/// 单个关键帧的 μs 域镜像（仅绘制/命中/菜单所需字段）。
/// v2 打包属性（2026-11-09）：value = 该键 v0 分量（标量值/向量第一分量）；
/// 时间轴只消费键时间点（菱形绘制/合并桶），value/interp 为键的完整语义
/// 保留（镜像结构不残缺；2026-11-10 行头下拉读数退役后暂无直接读者）。
struct TweenKeyDot {
    double t_us = 0.0;  // 片段本地时刻（μs，0..length()；拖拽中允许小数，回写时量化）
    double value = 0.0; // 键 v0 分量（业务域：位置/尺寸 px、旋转角度、不透明度 [0,1]）
    int    interp = 0;  // ms::TweenInterp: 0=Linear 1=Hold 2=Smooth
};

/// 单个 tween 通道的关键帧集合。prop = ms::TweenProp v2 打包枚举值
/// （1..9：位置/尺寸/旋转/不透明度/Z/角点 LT-RT-RB-LB），决定删除菜单
/// 色块与面板行指示色（时间轴菱形已统一白、不查色表）。
/// vmin/vmax = 适配器计算的【值域显示范围】（键值范围外扩 + 属性步长），
/// 曲线带与行头读数相继退役后暂无直接消费者，随结构保留（值域语义完备）。
struct TweenChannelDots {
    int prop = 0;
    std::vector<TweenKeyDot> keys;
    double vmin = 0.0; // 值域下界（曲线带底边）
    double vmax = 1.0; // 值域上界（曲线带顶边）
};
